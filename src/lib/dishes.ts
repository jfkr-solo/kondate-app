// ---------------------------------------------------------------------------
// 料理マスタ（初期データ）
// 材料は2人分。「食材 量単位」を「、」で区切って書く。
//   例: "鶏もも肉 300g、醤油 大さじ2、塩こしょう 少々"
// ---------------------------------------------------------------------------

const UNITS = "g|ml|個|本|丁|枚|パック|片|袋|切れ|尾|株|缶";

export function parseIngredients(src: string): IngredientLine[] {
  return src.split("、").map((part) => {
    const t = part.trim();
    const sp = t.lastIndexOf(" ");
    if (sp < 0) throw new Error(`材料の書式エラー: ${t}`);
    const name = t.slice(0, sp);
    const qty = t.slice(sp + 1);
    if (qty === "少々" || qty === "適量") return { name, amount: null, unit: qty };
    const spoon = qty.match(/^(大さじ|小さじ)(\d+(?:\.\d+)?)$/);
    if (spoon) return { name, amount: Number(spoon[2]), unit: spoon[1] as Unit };
    const m = qty.match(new RegExp(`^(\\d+(?:\\.\\d+)?)(${UNITS})$`));
    if (!m) throw new Error(`分量の書式エラー: ${t}`);
    return { name, amount: Number(m[1]), unit: m[2] as Unit };
  });
}

interface DishSeed {
  id: string;
  name: string;
  genre: Genre;
  category: Category;
  method: Method;
  flavor: Flavor;
  time: number;
  ing: string;
  steps: string[];
  equipment?: Equipment[];
  pasta?: boolean;
  group?: string;
  main?: string; // 主な食材（省略時は材料から自動判定）
}

const PROTEIN_KINDS = ["肉", "魚介", "卵", "大豆製品"];

function build(seed: DishSeed): Dish {
  const ingredients = parseIngredients(seed.ing);
  const infos = ingredients.map((l) => INGREDIENTS[l.name]);
  const isFish = infos.some((i) => i?.fish);
  let mainIngredient = seed.main;
  if (!mainIngredient) {
    const firstProtein = ingredients.find((l) =>
      PROTEIN_KINDS.includes(INGREDIENTS[l.name]?.kind ?? ""),
    );
    const firstNonSeasoning = ingredients.find(
      (l) => INGREDIENTS[l.name]?.kind !== "調味料" && INGREDIENTS[l.name]?.kind !== "主食",
    );
    mainIngredient =
      seed.category === "主菜"
        ? (firstProtein ?? firstNonSeasoning ?? ingredients[0]).name
        : (firstNonSeasoning ?? ingredients[0]).name;
  }
  const equipment = [...(seed.equipment ?? [])];
  if (seed.method === "揚げる" && !equipment.includes("揚げ鍋")) equipment.push("揚げ鍋");
  return {
    id: seed.id,
    name: seed.name,
    normalizedName: normalizeDishName(seed.name),
    group: seed.group,
    genre: seed.genre,
    category: seed.category,
    method: seed.method,
    flavor: seed.flavor,
    time: seed.time,
    servings: 2,
    ingredients,
    steps: seed.steps,
    equipment,
    isPasta: !!seed.pasta,
    isFried: seed.method === "揚げる",
    isFish: seed.category === "主菜" && isFish,
    mainIngredient,
  };
}

